def mat_label(name, image_name, fallback_scale=6.0):
    """Gold-on-black label driven by a mask (white = gold foil, embossed)."""
    m, nt, out = new_mat(name)
    gold = principled(nt, base=C_GOLD, metal=1.0, rough=0.2, aniso=0.3)
    black = principled(nt, base=(0.003, 0.003, 0.003, 1), rough=0.12, coat=1.0,
                       coat_rough=0.03)
    mix = nt.nodes.new("ShaderNodeMixShader")
    uv = nt.nodes.new("ShaderNodeTexCoord")
    img = load_image(image_name)
    if img is not None:
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.image = img
        tex.interpolation = "Cubic"
        nt.links.new(uv.outputs["UV"], tex.inputs["Vector"])
        fac = tex.outputs["Color"]
    else:  # procedural stand-in: gold brick lattice
        tex = nt.nodes.new("ShaderNodeTexBrick")
        tex.inputs["Scale"].default_value = fallback_scale
        tex.inputs["Color1"].default_value = (0, 0, 0, 1)
        tex.inputs["Color2"].default_value = (0, 0, 0, 1)
        tex.inputs["Mortar"].default_value = (1, 1, 1, 1)
        nt.links.new(uv.outputs["UV"], tex.inputs["Vector"])
        fac = tex.outputs["Color"]
    bw = nt.nodes.new("ShaderNodeRGBToBW")
    nt.links.new(fac, bw.inputs[0])
    bump = nt.nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 0.6
    bump.inputs["Distance"].default_value = 0.0015
    nt.links.new(bw.outputs[0], bump.inputs["Height"])
    nt.links.new(bump.outputs["Normal"], gold.inputs["Normal"])
    nt.links.new(bw.outputs[0], mix.inputs[0])
    nt.links.new(black.outputs[0], mix.inputs[1])
    nt.links.new(gold.outputs[0], mix.inputs[2])
    nt.links.new(mix.outputs[0], out.inputs[0])
    return m


