def make_cam(shot, lens, keys, fstop=None, interp="LINEAR"):
    """keys: list of (frame, cam_location, target_location)."""
    cd = bpy.data.cameras.new(f"CAM_{shot:02d}")
    cd.lens = lens
    cd.sensor_fit = "AUTO"
    cd.clip_start = 0.02
    cd.clip_end = 3000
    cam = new_obj(f"CAM_{shot:02d}", cd, "CAMERAS")
    tgt = empty(f"CAM_{shot:02d}_Target", keys[0][2], "CAMERAS", 0.1)
    con = cam.constraints.new("TRACK_TO")
    con.target = tgt
    con.track_axis = "TRACK_NEGATIVE_Z"
    con.up_axis = "UP_Y"
    for f, loc, tl in keys:
        key(cam, "location", f, Vector(loc), interp)
        key(tgt, "location", f, Vector(tl), interp)
    if fstop:
        cd.dof.use_dof = True
        cd.dof.focus_object = tgt
        cd.dof.aperture_fstop = fstop
        cd.dof.aperture_blades = 7
    CAMS[shot] = cam
    return cam, tgt


