def validate(scene):
    problems = []
    for img in bpy.data.images:
        if img.source == "FILE" and not img.packed_file and not os.path.exists(
                bpy.path.abspath(img.filepath)):
            problems.append(f"missing texture: {img.filepath}")
    for shot, (s, e) in SHOTS.items():
        mk = [m for m in scene.timeline_markers if m.frame == s]
        if not mk or mk[0].camera is None:
            problems.append(f"shot {shot}: no camera marker")
    covered = sorted(f for s, e in SHOTS.values() for f in range(s, e + 1))
    if covered != list(range(1, FRAME_END + 1)):
        problems.append("timeline: shots do not cover 1-384 exactly")
    r = scene.render
    ratio = r.resolution_x / r.resolution_y
    if abs(ratio - 9 / 16) > 1e-3:
        problems.append(f"aspect ratio {ratio:.3f} is not 9:16")
    if scene.frame_end != FRAME_END or r.fps != FPS:
        problems.append("frame range / fps wrong")
    body = bpy.data.objects["Bottle_Body"].dimensions
    cap = bpy.data.objects["Bottle_Cap"].dimensions
    if abs(body.x / body.z - 1.0) > 0.02 or abs(cap.x / body.x - 0.357) > 0.02:
        problems.append("bottle proportions drifted")
    for ob in bpy.data.objects:
        if ob.type == "FONT" and ob.data.font and ob.data.font.filepath == "<builtin>":
            problems.append(f"{ob.name}: using builtin font (font file missing)")
    print("[QAF] validation:", "OK" if not problems else "")
    for p in problems:
        print("   -", p)
    print(f"[QAF] {r.resolution_x}x{r.resolution_y} @ {r.fps} fps, frames {scene.frame_start}-"
          f"{scene.frame_end}, {len(SHOTS)} shots, cameras: {len(CAMS)}")
    return problems


def bake_particles(scene):
    for ob in bpy.data.objects:
        for ps in getattr(ob, "particle_systems", []):
            ps.point_cache.use_disk_cache = False
    try:
        with bpy.context.temp_override(scene=scene):
            bpy.ops.ptcache.bake_all(bake=True)
        print("[QAF] particles baked")
    except Exception as ex:
        print("[QAF] particle bake skipped:", ex)


