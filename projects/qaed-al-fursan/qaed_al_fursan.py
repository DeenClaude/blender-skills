# Render settings
# ---------------------------------------------------------------------------
def configure_render(scene, quality, out_dir, png=False):
    r = scene.render
    r.engine = "CYCLES"
    r.fps = FPS
    scene.frame_start, scene.frame_end = 1, FRAME_END
    if quality == "final":
        r.resolution_x, r.resolution_y = 1080, 1920
        samples, step = 64, 1.0
        r.use_motion_blur = True
        r.motion_blur_shutter = 0.35
    else:
        r.resolution_x, r.resolution_y = 360, 640
        samples, step = 12, 3.0
        r.use_motion_blur = False
    r.resolution_percentage = 100
    r.use_persistent_data = True      # keep static geometry/BVH between frames
    c = scene.cycles
    c.device = "CPU"
    c.samples = samples
    c.use_adaptive_sampling = True
    c.adaptive_threshold = 0.02 if quality == "final" else 0.08
    c.use_denoising = True
    try:
        c.denoiser = "OPENIMAGEDENOISE"
    except Exception:
        pass
    c.max_bounces = 8
    c.diffuse_bounces = 3
    c.glossy_bounces = 4
    c.transmission_bounces = 8
    c.volume_bounces = 0
    c.caustics_reflective = False
    c.caustics_refractive = False
    c.blur_glossy = 1.0
    c.volume_step_rate = step
    c.volume_max_steps = 256 if quality == "final" else 96
    c.sample_clamp_indirect = 8.0
    scene.view_settings.view_transform = "AgX"
    for look in ("AgX - Punchy", "Punchy", "AgX - Medium High Contrast"):
        try:
            scene.view_settings.look = look
            break
        except TypeError:
            continue
    r.film_transparent = False

    os.makedirs(out_dir, exist_ok=True)
    tag = "preview" if quality != "final" else "final"
    if png:
        r.image_settings.file_format = "PNG"
        r.image_settings.color_mode = "RGB"
        r.filepath = os.path.join(out_dir, f"frames_{tag}", "f_####")
        r.use_overwrite = False
        r.use_placeholder = True
    else:
        if hasattr(r.image_settings, "media_type"):       # Blender 5.x
            r.image_settings.media_type = "VIDEO"
        r.image_settings.file_format = "FFMPEG"
        r.ffmpeg.format = "MPEG4"
        r.ffmpeg.codec = "H264"
        r.ffmpeg.constant_rate_factor = "HIGH" if tag == "final" else "MEDIUM"
        r.ffmpeg.ffmpeg_preset = "GOOD"
        r.ffmpeg.audio_codec = "NONE"
        r.filepath = os.path.join(out_dir, f"qaed_al_fursan_{tag}_")


