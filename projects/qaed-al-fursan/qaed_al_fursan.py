def particle_instance(name, radius, mat):
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=1, radius=radius)
    o = mesh_from_bm(name, bm, "PARTICLES")
    o.data.materials.append(mat)
    o.location = (0, 0, -1000)
    return o


def emitter_box(name, loc, size):
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    bmesh.ops.scale(bm, vec=size, verts=bm.verts)
    o = mesh_from_bm(name, bm, "PARTICLES", smooth=False)
    o.location = loc
    o.show_instancer_for_render = False
    o.show_instancer_for_viewport = False
    o.display_type = "WIRE"
    return o


def particle_system(emitter, name, inst, count, start, end, life, emit_from="VOLUME",
                    normal=0.0, rand=0.0, gravity=1.0, brownian=0.0, damping=0.0,
                    size=1.0, size_rand=0.5, obj_vel=None, seed=1):
    mod = emitter.modifiers.new(name, "PARTICLE_SYSTEM")
    ps = mod.particle_system
    ps.seed = seed
    s = ps.settings
    s.name = name
    s.count = count
    s.frame_start = start
    s.frame_end = end
    s.lifetime = life
    s.lifetime_random = 0.4
    s.emit_from = emit_from
    s.use_emit_random = True
    s.distribution = "RAND"
    s.normal_factor = normal
    s.factor_random = rand
    s.physics_type = "NEWTON"
    s.effector_weights.gravity = gravity
    s.brownian_factor = brownian
    s.damping = damping
    s.render_type = "OBJECT"
    s.instance_object = inst
    s.particle_size = size
    s.size_random = size_rand
    s.use_rotations = True
    s.rotation_mode = "NONE"
    s.use_dynamic_rotation = False
    if obj_vel is not None:
        s.object_factor = obj_vel
    ps.point_cache.frame_start = max(1, start)
    ps.point_cache.frame_end = FRAME_END
    return ps


