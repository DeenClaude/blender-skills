def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    a = {"quality": "preview", "render": False, "png": False, "frames": None,
         "still": [], "out": os.path.join(HERE, "render"), "save": True,
         "emblem": False, "samples": None, "mblur": True, "horse3d": False}
    i = 0
    while i < len(argv):
        t = argv[i]
        if t == "--quality":
            a["quality"] = argv[i + 1]; i += 1
        elif t == "--render":
            a["render"] = True
        elif t == "--png":
            a["png"] = True
        elif t == "--frames":
            s, e = argv[i + 1].split("-"); a["frames"] = (int(s), int(e)); i += 1
        elif t == "--still":
            while i + 1 < len(argv) and not argv[i + 1].startswith("--"):
                a["still"].append(int(argv[i + 1])); i += 1
        elif t == "--out":
            a["out"] = os.path.abspath(argv[i + 1]); i += 1
        elif t == "--no-save":
            a["save"] = False
        elif t == "--samples":
            a["samples"] = int(argv[i + 1]); i += 1
        elif t == "--horse-3d":
            a["horse3d"] = True
        elif t == "--no-mblur":
            a["mblur"] = False
        elif t == "--emblem":
            a["emblem"] = True
        i += 1
    return a


