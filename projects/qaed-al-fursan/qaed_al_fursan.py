def dune_height(x, y):
    """Procedural dune field (numpy or float). Sharp crests, smooth troughs,
    flattened near the action area around the origin."""
    wx = x + 18 * np.sin(y * 0.011 + 1.3) + 9 * np.sin(y * 0.031)
    wy = y + 14 * np.sin(x * 0.013 + 0.4)
    a = (wx * 0.6 + wy * 0.8) * 0.018
    r1 = 1 - np.abs(np.sin(a))
    b = (-wx * 0.7 + wy * 0.7) * 0.031
    r2 = 1 - np.abs(np.sin(b + 0.7))
    h = 11 * r1 ** 2.2 + 3.5 * r2 ** 2 + 1.2 * np.sin(x * 0.05) * np.sin(y * 0.04)
    d = np.sqrt((x / 50.0) ** 2 + (y / 45.0) ** 2)
    m = np.clip((d - 0.55) / 0.9, 0, 1)
    m = m * m * (3 - 2 * m)
    crest = 2.4 * np.exp(-((y - 12.0) / 5.5) ** 2) * np.exp(-((x + 3.0) / 30.0) ** 2)
    return h * (0.18 + 0.82 * m) + 0.4 * np.sin(x * 0.11 + y * 0.07) + crest


def build_desert():
    n = 520
    xs = np.linspace(-700, 700, n)
    ys = np.linspace(-400, 1100, n)
    X, Y = np.meshgrid(xs, ys)
    Z = dune_height(X, Y)
    verts = np.stack([X.ravel(), Y.ravel(), Z.ravel()], axis=1)
    idx = np.arange(n * n).reshape(n, n)
    a = idx[:-1, :-1].ravel(); b = idx[:-1, 1:].ravel()
    c = idx[1:, 1:].ravel(); d = idx[1:, :-1].ravel()
    faces = np.stack([a, b, c, d], axis=1)
    me = bpy.data.meshes.new("Desert_Dunes")
    me.vertices.add(len(verts))
    me.vertices.foreach_set("co", verts.astype(np.float32).ravel())
    me.loops.add(faces.size)
    me.loops.foreach_set("vertex_index", faces.astype(np.int32).ravel())
    me.polygons.add(len(faces))
    me.polygons.foreach_set("loop_start", (np.arange(len(faces)) * 4).astype(np.int32))
    me.update(calc_edges=True)
    me.polygons.foreach_set("use_smooth", np.ones(len(faces), dtype=bool))
    dunes = new_obj("Desert_Dunes", me, "ENVIRONMENT")
    dunes.data.materials.append(mat_sand())

    # Atmospheric haze / god rays: homogeneous volume over the desert
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    bmesh.ops.scale(bm, vec=(1400, 1500, 160), verts=bm.verts)
    bmesh.ops.translate(bm, vec=(0, 350, 60), verts=bm.verts)
    fog = mesh_from_bm("Desert_Haze", bm, "ENVIRONMENT", smooth=False)
    m, nt, out = new_mat("M_DesertHaze")
    pv = nt.nodes.new("ShaderNodeVolumePrincipled")
    pv.inputs["Color"].default_value = (1.0, 0.72, 0.42, 1)
    pv.inputs["Density"].default_value = 0.00035
    pv.inputs["Anisotropy"].default_value = 0.65
    nt.links.new(pv.outputs[0], out.inputs["Volume"])
    fog.data.materials.append(m)
    fog.visible_shadow = False
    return dunes, fog


def build_rock(name, loc, seed=3):
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=5, radius=1.0)
    random.seed(seed)
    off = Vector((random.random() * 50, random.random() * 50, 0))
    for v in bm.verts:
        p = v.co
        n = noise.fractal(p * 1.3 + off, 0.6, 2.0, 4)
        rg = noise.ridged_multi_fractal(p * 2.2 + off, 0.8, 2.0, 4, 1.0, 2.0)
        p *= 1.0 + 0.30 * n + 0.07 * rg
    bmesh.ops.scale(bm, vec=(1.25, 0.95, 0.55), verts=bm.verts)
    top = 0.42
    for v in bm.verts:
        if v.co.z > top:
            v.co.z = top + (v.co.z - top) * 0.05
    rock = mesh_from_bm(name, bm, "ENVIRONMENT", smooth=True)
    rock.location = loc
    m, nt, out = new_mat("M_Rock_" + name)
    p = principled(nt, rough=0.85)
    tc = nt.nodes.new("ShaderNodeTexCoord")
    nz = nt.nodes.new("ShaderNodeTexNoise")
    nz.inputs["Scale"].default_value = 4.0
    nz.inputs["Detail"].default_value = 12.0
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp.color_ramp.elements[0].color = (0.05, 0.03, 0.018, 1)
    ramp.color_ramp.elements[1].color = (0.22, 0.13, 0.07, 1)
    nt.links.new(tc.outputs["Object"], nz.inputs["Vector"])
    nt.links.new(nz.outputs["Fac"], ramp.inputs["Fac"])
    nt.links.new(ramp.outputs["Color"], p.inputs["Base Color"])
    vor = nt.nodes.new("ShaderNodeTexVoronoi")
    vor.inputs["Scale"].default_value = 7.0
    nt.links.new(tc.outputs["Object"], vor.inputs["Vector"])
    bump = nt.nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 1.0
    mx = nt.nodes.new("ShaderNodeMath"); mx.operation = "ADD"
    nt.links.new(vor.outputs["Distance"], mx.inputs[0])
    nt.links.new(nz.outputs["Fac"], mx.inputs[1])
    nt.links.new(mx.outputs[0], bump.inputs["Height"])
    nt.links.new(bump.outputs["Normal"], p.inputs["Normal"])
    nt.links.new(p.outputs[0], out.inputs[0])
    rock.data.materials.append(m)
    return rock, loc.z + top


