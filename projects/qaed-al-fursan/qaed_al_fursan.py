    rings = []
    for i in range(seg):
        a = 2 * math.pi * i / seg
        sc = 1.0 + 0.15 * max(0.0, -math.cos(a))   # fuller at the back
        rings.append([bm.verts.new((r * math.cos(a) * sc, r * math.sin(a) * 0.9, z)) for r, z in prof])
