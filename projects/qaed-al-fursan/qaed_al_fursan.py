def build_arabic_title(name, width, coll="BRAND_ELEMENTS", extrude=0.03, bevel=0.006):
    """Builds قائد الفرسان as real 3D curves from correctly shaped outlines
    (assets/arabic_title.json, made by make_assets.py with HarfBuzz + Amiri).
    Blender's own text object cannot shape Arabic, so this avoids broken,
    unjoined letters."""
    path = os.path.join(ASSETS, "arabic_title.json")
    if not os.path.exists(path):
        print("[QAF] arabic_title.json missing - Arabic title skipped")
        return None
    data = json.load(open(path))
    sx = width / data["width"]
    cu = bpy.data.curves.new(name, "CURVE")
    cu.dimensions = "2D"
    cu.fill_mode = "BOTH"
    cu.extrude = extrude
    cu.bevel_depth = bevel
    cu.bevel_resolution = 2
    cx, cy = data["width"] / 2, data["height"] / 2 + data["ymin"]
    for ring in data["rings"]:
        sp = cu.splines.new("POLY")
        sp.points.add(len(ring) - 1)
        for i, (x, y) in enumerate(ring):
            sp.points[i].co = ((x - cx) * sx, (y - cy) * sx, 0, 1)
        sp.use_cyclic_u = True
    return new_obj(name, cu, coll)


def text_obj(name, body, size, font_file, spacing=1.0, extrude=0.01, coll="BRAND_ELEMENTS"):
    cu = bpy.data.curves.new(name, "FONT")
    cu.body = body
    cu.size = size
    cu.align_x = "CENTER"
    cu.align_y = "CENTER"
    cu.space_character = spacing
    cu.extrude = extrude
    cu.bevel_depth = extrude * 0.25
    fp = os.path.join(ASSETS, "fonts", font_file)
    if os.path.exists(fp):
        cu.font = bpy.data.fonts.load(fp, check_existing=True)
    return new_obj(name, cu, coll)


