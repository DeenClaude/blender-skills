COLL = {}


def reset_scene():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.name = "QAED_AL_FURSAN"
    return scene


def make_collections(scene):
    names = ["PRODUCT", "LABEL", "ENVIRONMENT", "LIGHTING", "CAMERAS",
             "PARTICLES", "ANIMATION", "BRAND_ELEMENTS"]
    for n in names:
        c = bpy.data.collections.new(n)
        COLL[n] = c
    root = scene.collection
    for n in names:
        if n == "LABEL":
            COLL["PRODUCT"].children.link(COLL[n])   # label travels with the product instances
        else:
            root.children.link(COLL[n])


def link(obj, coll):
    for c in list(obj.users_collection):
        c.objects.unlink(obj)
    COLL[coll].objects.link(obj)
    return obj


def new_obj(name, data, coll):
    o = bpy.data.objects.new(name, data)
    COLL[coll].objects.link(o)
    return o


def empty(name, loc, coll="ANIMATION", size=0.2):
    e = bpy.data.objects.new(name, None)
    e.empty_display_size = size
    e.location = loc
    COLL[coll].objects.link(e)
    return e


def mesh_from_bm(name, bm, coll, smooth=True):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    if smooth:
        for p in me.polygons:
            p.use_smooth = True
    return new_obj(name, me, coll)


def action_fcurves(id_data):
    """All F-curves of an ID's action (Blender 4.x flat actions and the
    5.x layered actions / channel bags)."""
    ad = id_data.animation_data
    if ad is None or ad.action is None:
        return []
    act = ad.action
    if hasattr(act, "layers") and len(act.layers):
        out = []
        for layer in act.layers:
            for strip in layer.strips:
                cb = strip.channelbag(ad.action_slot) if ad.action_slot else None
                if cb:
                    out.extend(cb.fcurves)
        return out
    return list(getattr(act, "fcurves", []))


def key(target, path, frame, value=None, interp="BEZIER"):
    """Insert a keyframe and force its interpolation explicitly."""
    if value is not None:
        setattr(target, path, value)
    target.keyframe_insert(data_path=path, frame=frame)
    try:
        full = target.path_from_id(path)
    except Exception:
        full = path
    for fc in action_fcurves(target.id_data):
        if fc.data_path == full:
            for kp in fc.keyframe_points:
                if abs(kp.co.x - frame) < 0.01:
                    kp.interpolation = interp


def key_visible(obj, frames_on):
    """Render-visible only inside the given shot list (constant keys)."""
    ranges = sorted(SHOTS[s] for s in frames_on)
    key(obj, "hide_render", 1, True, "CONSTANT")
    key(obj, "hide_viewport", 1, True, "CONSTANT")
    for s, e in ranges:
        key(obj, "hide_render", s, False, "CONSTANT")
        key(obj, "hide_viewport", s, False, "CONSTANT")
        key(obj, "hide_render", e + 1, True, "CONSTANT")
        key(obj, "hide_viewport", e + 1, True, "CONSTANT")


def smoothstep(a, b, x):
    t = min(max((x - a) / (b - a), 0.0), 1.0)
    return t * t * (3 - 2 * t)


